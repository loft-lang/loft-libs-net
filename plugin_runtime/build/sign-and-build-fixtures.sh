# ZT-E — build the reference plugin wasm and the four-case test fixtures.
# Reproducible from scratch: (re)generate two keypairs, build the wasm shim,
# and sign it with the trusted author A and the untrusted author B.
#
# Prereqs:
#   * loft-keygen built:  cargo build --release --bin loft-keygen --features registry
#   * wasm32-unknown-unknown target installed
# Usage: tools/zt-e-plugin-staging/build/sign-and-build-fixtures.sh [--keep-keys]
set -euo pipefail

STAGING="$(cd "$(dirname "$0")/.." && pwd)"
cd "$STAGING"

KEYGEN="${LOFT_KEYGEN:-$STAGING/../../target/release/loft-keygen}"
if [[ ! -x "$KEYGEN" ]]; then
  echo "loft-keygen not found at $KEYGEN" >&2
  echo "  build it: cargo build --release --bin loft-keygen --features registry" >&2
  exit 1
fi

echo "==> building reference plugin wasm"
( cd reference-plugin/wasm-shim && cargo build --release --target wasm32-unknown-unknown )
cp reference-plugin/wasm-shim/target/wasm32-unknown-unknown/release/counter_plugin.wasm build/counter_plugin.wasm
echo "    build/counter_plugin.wasm ($(wc -c < build/counter_plugin.wasm) bytes)"

if [[ "${1:-}" != "--keep-keys" || ! -f keys/authorA/registry-signing-key.bin ]]; then
  echo "==> generating two Ed25519 keypairs (author A = trusted, B = untrusted)"
  rm -rf keys
  mkdir -p keys/authorA keys/authorB
  ( cd keys/authorA && "$KEYGEN" generate >/dev/null )
  ( cd keys/authorB && "$KEYGEN" generate >/dev/null )
  # The private key (.bin) and loft-keygen's own .pub name are gitignored by the
  # repo root .gitignore (so real registry keys never get committed).  Copy the
  # PUBLIC key to a non-ignored name the tests read; the private key stays local
  # (these are throwaway TEST keys, regenerated by re-running this script).
  cp keys/authorA/registry-signing-key.pub keys/authorA/public_key.hex
  cp keys/authorB/registry-signing-key.pub keys/authorB/public_key.hex
fi
echo "    trusted   A pub: $(cat keys/authorA/public_key.hex)"
echo "    untrusted B pub: $(cat keys/authorB/public_key.hex)"

if [[ -f keys/authorA/registry-signing-key.bin && -f keys/authorB/registry-signing-key.bin ]]; then
  echo "==> signing the wasm with A (trusted) and B (untrusted)"
  "$KEYGEN" sign --in build/counter_plugin.wasm --key keys/authorA/registry-signing-key.bin --out build/counter_plugin.wasm.sig  >/dev/null
  "$KEYGEN" sign --in build/counter_plugin.wasm --key keys/authorB/registry-signing-key.bin --out build/counter_plugin.wasm.sigB >/dev/null
  echo "    build/counter_plugin.wasm.sig  (A, trusted)"
  echo "    build/counter_plugin.wasm.sigB (B, untrusted)"
else
  # Fresh checkout: private keys are gitignored, but the committed wasm + .sig +
  # public_key.hex are already a consistent set, so no re-sign is needed.  Drop
  # --keep-keys to regenerate keys and re-sign from scratch.
  echo "==> private keys absent — using the committed .sig fixtures as-is"
  echo "    (run WITHOUT --keep-keys to regenerate keypairs and re-sign)"
fi

echo "==> done. fixtures ready for the host + browser security-gate tests."
